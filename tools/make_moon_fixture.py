"""Builds a synthetic Moon Reader backup (.mrstd) for Quill's on-device import test.

Same structure as a real backup (numbered .tag files named by _names.list; mrbooks.db with
books/statistics/notes; positions10.xml) but every value is invented. Writes the archive as
base64 into mobile/integration_test/moon_fixture.dart.

Usage: python3 -I tools/make_moon_fixture.py
"""
import base64, io, os, sqlite3, sys, tempfile, zipfile

ROOT = '/sdcard/Download/Books'
BOOKS = [
    # path, title, author, category, addTime
    (f'{ROOT}/Saga/First Light.epub', 'First Light', 'Ada Inkwell', '<The Lamp Saga>\n#1.0#\n(fantasy)\n', 1780000000000),
    (f'{ROOT}/Saga/Second Dark.epub', 'Second Dark', 'Ada Inkwell', '<The Lamp Saga>\n#2.0#\n', 1780000000100),
    (f'{ROOT}/Gone Away.epub', 'Gone Away', 'Nobody', '', 1780000000200),
]
STATS = [
    (f'{ROOT}/Saga/First Light.epub', '20400|600000@3000 #40.5%\n20401|1200000@6000 #100%\n'),
    (f'{ROOT}/Saga/Second Dark.epub', '20402|300000@1500 #12%\n'),
]
POSITIONS = {
    f'{ROOT.lower()}/saga/first light.epub': '9@0#120:100%',
    f'{ROOT.lower()}/saga/second dark.epub': '2@0#40:12%',
}

def build() -> bytes:
    with tempfile.TemporaryDirectory() as d:
        db = os.path.join(d, 'mrbooks.db')
        c = sqlite3.connect(db)
        c.execute('create table books (_id integer primary key, book text, filename text, lowerFilename text, author text, description text, category text, thumbFile text, coverFile text, addTime text, favorite text, downloadUrl text, rate text, bak1 text, bak2 text)')
        c.execute('create table statistics (_id integer primary key, filename text, usedTime numeric, readWords numeric, dates text)')
        c.execute('create table notes (_id integer primary key, book text, filename text, lowerFilename text, lastChapter numeric, lastSplitIndex numeric, lastPosition numeric, highlightLength numeric, highlightColor numeric, time numeric, bookmark text, note text, original text, underline numeric, strikethrough numeric, bak text)')
        for path, title, author, cat, added in BOOKS:
            c.execute('insert into books (book, filename, lowerFilename, author, description, category, addTime, favorite, rate) values (?,?,?,?,?,?,?,?,?)',
                      (title, path, path.lower(), author, 'An invented book.', cat, str(added), '', '0'))
        for path, dates in STATS:
            c.execute('insert into statistics (filename, usedTime, readWords, dates) values (?,?,?,?)', (path, 0, 0, dates))
        c.execute('insert into notes (book, filename, lowerFilename, lastChapter, lastSplitIndex, lastPosition, highlightLength, highlightColor, time, bookmark, note, original, underline, strikethrough, bak) values (?,?,?,?,?,?,?,?,?,?,?,?,?,?,?)',
                  ('First Light', BOOKS[0][0], BOOKS[0][0].lower(), 3, 0, 120, 9, -256, 1780000000300, '', '', 'lamp glow', 0, 0, ''))
        c.commit(); c.close()
        xml = "<?xml version='1.0' encoding='utf-8' standalone='yes' ?>\n<map>\n" + ''.join(
            f'    <string name="{k}">{v}</string>\n' for k, v in POSITIONS.items()) + '</map>\n'
        names = ['com.flyersoft.moonreader/databases/mrbooks.db',
                 'com.flyersoft.moonreader/shared_prefs/options1002.xml',
                 'com.flyersoft.moonreader/shared_prefs/positions10.xml']
        out = io.BytesIO()
        with zipfile.ZipFile(out, 'w', zipfile.ZIP_DEFLATED) as z:
            z.writestr('com.flyersoft.moonreader/_names.list', '\n'.join(names) + '\n')
            z.write(db, 'com.flyersoft.moonreader/1.tag')
            z.writestr('com.flyersoft.moonreader/2.tag', '<map><string name="theme">not read</string></map>')
            z.writestr('com.flyersoft.moonreader/3.tag', xml)
        return out.getvalue()

if __name__ == '__main__':
    data = base64.b64encode(build()).decode()
    lines = [data[i:i + 100] for i in range(0, len(data), 100)]
    target = os.path.join(os.path.dirname(__file__), '..', 'mobile', 'integration_test', 'moon_fixture.dart')
    with open(target, 'w') as f:
        f.write('// Generated by tools/make_moon_fixture.py: a synthetic Moon Reader backup (invented data).\n')
        f.write('// ignore_for_file: lines_longer_than_80_chars\n')
        f.write("const syntheticMoonBackup =\n")
        f.write('\n'.join(f"    '{l}'" for l in lines) + ';\n')
    print('wrote', os.path.normpath(target), len(data), 'base64 chars')
